import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import multer from 'multer';
import { config } from '../config.js';
import { HttpError } from './http.js';

export const MAX_IMAGE_BYTES = 5 * 1024 * 1024;
export const MAX_IMAGES_PER_PROPERTY = 12;

/** Files are held in memory (max 8 x 5 MB) and only written to disk after their bytes are verified. */
export const imageUpload = multer({
  storage: multer.memoryStorage(),
  limits: { fileSize: MAX_IMAGE_BYTES, files: 8, fields: 5 },
});

/** Detects the real file type from magic bytes; the client-supplied MIME type and filename are never trusted. */
export function sniffImageType(buf: Buffer): 'jpg' | 'png' | 'webp' | null {
  if (buf.length >= 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return 'jpg';
  if (buf.length >= 8 && buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])))
    return 'png';
  if (buf.length >= 12 && buf.toString('ascii', 0, 4) === 'RIFF' && buf.toString('ascii', 8, 12) === 'WEBP') return 'webp';
  return null;
}

const STORAGE_KEY = /^[0-9a-f]{32}\.(jpg|png|webp)$/;

/** Writes a verified image under a random name. Returns the storage key (the only thing persisted). */
export async function storeImage(buf: Buffer): Promise<string> {
  const ext = sniffImageType(buf);
  if (!ext) throw new HttpError(400, 'Only JPEG, PNG or WebP images are allowed');
  const key = `${crypto.randomBytes(16).toString('hex')}.${ext}`;
  await fs.mkdir(config.uploadDir, { recursive: true });
  await fs.writeFile(path.join(config.uploadDir, key), buf, { flag: 'wx' });
  return key;
}

export async function removeImage(key: string | null) {
  // Keys are generated by us, but validate anyway so a tampered row can never escape the upload dir
  if (!key || !STORAGE_KEY.test(key)) return;
  await fs.rm(path.join(config.uploadDir, key), { force: true });
}
